// Generate the shared retention-policy digest vectors.
//
// WO-C3. `lib/leaf/retentionPolicy.ts` and
// `packages/scruple-api/scruple_api/retention.py` are two implementations of
// one digest, and a digest is only a binding if two parties independently
// arrive at the same one from the same policy. This file is what stops them
// drifting — the same job `test/vectors/ratchet-vectors.json` does for the key
// schedule and `component-preimage-vectors.json` does for the field set.
//
// ⚑ THE VECTORS ARE GENERATED FROM THE TYPESCRIPT AND RECOMPUTED BY THE
// PYTHON. `tests/test_retention_policy.py` calls its own implementation on
// each `policy` below and asserts the digest and the canonical bytes match. A
// Python module that read the digest out of this file would agree by
// construction and would go on agreeing after the TypeScript changed.
//
// The REFUSED cases matter as much as the accepted ones: a policy with no
// canonical form must be refused in both languages, or one of them will emit a
// digest the other cannot check.

import fs from 'node:fs';
import path from 'node:path';
import {
  canonicalRetentionPolicy,
  retentionPolicyDigest,
  validateRetentionPolicy,
  DEFAULT_RETENTION_POLICY,
} from '../lib/leaf/retentionPolicy.ts';

const accepted = [
  {
    name: 'the default policy — thirty days of evidence, one day to settle',
    note:
      'Seeded by migration 055 with this digest as a SQL literal. A deployment that enrols ' +
      'nothing emits under it, so its digest resolves rather than being refused at ingest.',
    policy: DEFAULT_RETENTION_POLICY,
  },
  {
    name: 'the same policy_id with a LONGER retention — a different digest',
    note:
      'THE WHOLE POINT OF THE FIELD. Identity is unchanged and the digest is not, which is ' +
      'what "binds duration, not identity" means. A digest over the name alone would be ' +
      'equal here, and a verifier following it after the evidence was reaped could not tell ' +
      'that from a forged handle.',
    policy: { ...DEFAULT_RETENTION_POLICY, retention_duration_s: 30 * 24 * 3600 + 1 },
  },
  {
    name: 'the same policy_id with a shorter settlement window — also a different digest',
    note: 'Both durations are inside the digest, not only the retention one.',
    policy: { ...DEFAULT_RETENTION_POLICY, settlement_window_s: 3600 },
  },
  {
    name: 'a one-second policy — the shape the tests use to make evidence expire',
    note:
      'Legal: settlement_window_s <= retention_duration_s. It exists so an expiry can be ' +
      'observed in a test rather than asserted about a month from now.',
    policy: {
      version: 1,
      policy_id: 'wo-c3-one-second',
      clock: 'scruple-witness-v2',
      retention_duration_s: 1,
      settlement_window_s: 1,
    },
  },
];

const refused = [
  {
    name: 'a settlement window LONGER than the retention duration',
    why: 'the gap becomes terminal after the evidence needed to settle it is gone',
    policy: { ...DEFAULT_RETENTION_POLICY, settlement_window_s: 60 * 24 * 3600 },
  },
  {
    name: "the emitter's own clock, under a name that sounds like an institution",
    why: 'a deadline counted on `local` is the config-inherited field class the council refused',
    policy: { ...DEFAULT_RETENTION_POLICY, clock: 'local' },
  },
  {
    name: 'a retention duration of zero',
    why: 'evidence that is never kept cannot be resolved even once',
    policy: { ...DEFAULT_RETENTION_POLICY, retention_duration_s: 0, settlement_window_s: 0 },
  },
  {
    name: 'an extra key nobody hashes on the other side',
    why: 'a field outside the agreed set is a field one implementation digests and the other drops',
    policy: { ...DEFAULT_RETENTION_POLICY, grace_period_s: 3600 },
  },
];

const out = {
  note:
    'GENERATED by scripts/gen-retention-policy-vectors.mjs. WO-C3. Two implementations of ' +
    'one digest: lib/leaf/retentionPolicy.ts and packages/scruple-api/scruple_api/retention.py. ' +
    'The Python RECOMPUTES these rather than reading them, or it would agree by construction.',
  accepted: accepted.map((c) => ({
    ...c,
    canonical_json: canonicalRetentionPolicy(c.policy),
    digest: retentionPolicyDigest(c.policy),
  })),
  refused: refused.map((c) => ({
    ...c,
    typescript_reason: validateRetentionPolicy(c.policy).reason ?? null,
  })),
};

const dest = path.join(process.cwd(), 'test', 'vectors', 'retention-policy-vectors.json');
fs.writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log(`[gen] wrote ${dest}`);
